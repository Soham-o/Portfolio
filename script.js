document.addEventListener('DOMContentLoaded', () => {

    // ── 1. THEME ─────────────────────────────────────────────
    const body    = document.body;
    const themeBtn = document.getElementById('theme-switcher');
    const savedTheme = localStorage.getItem('theme');

    if (savedTheme === 'light') {
        body.classList.remove('dark-mode');
    } else {
        body.classList.add('dark-mode');
    }

    if (themeBtn) {
        themeBtn.addEventListener('click', () => {
            body.classList.toggle('dark-mode');
            localStorage.setItem('theme', body.classList.contains('dark-mode') ? 'dark' : 'light');
        });
    }

    // ── 2. PAGE TRANSITIONS ───────────────────────────────────
    const loader = document.querySelector('.transition-loader');

    if (loader) {
        loader.classList.add('transition-active');
        setTimeout(() => loader.classList.remove('transition-active'), 1500);
    }

    document.querySelectorAll('a').forEach(link => {
        link.addEventListener('click', (e) => {
            const href   = link.getAttribute('href');
            const target = link.getAttribute('target');
            if (loader && href && !href.startsWith('#') && target !== '_blank' && !href.includes('mailto')) {
                e.preventDefault();
                loader.classList.add('transition-exit');
                setTimeout(() => { window.location.href = href; }, 600);
            }
        });
    });

    // ── 3. TIMELINE SCROLL ───────────────────────────────────
    // Works for: experience, education, journey-story, journey-milestones
    function setupTimeline(sectionId) {
        const section = document.getElementById(sectionId);
        if (!section) return;

        const container    = section.querySelector('.timeline-container');
        const lineProgress = section.querySelector('.scroll-line-progress');
        const items        = section.querySelectorAll('.timeline-item');

        if (!container || !lineProgress) return;

        window.addEventListener('scroll', () => {
            const rect       = container.getBoundingClientRect();
            const startPoint = window.innerHeight * 0.8;
            let pct = ((startPoint - rect.top) / (rect.height * 1.2)) * 100;
            pct = Math.max(0, Math.min(pct, 100));
            lineProgress.style.height = `${pct}%`;

            items.forEach(item => {
                if (item.getBoundingClientRect().top < startPoint) {
                    item.classList.add('active');
                } else {
                    item.classList.remove('active');
                }
            });
        });
    }

    setupTimeline('experience');
    setupTimeline('education');
    setupTimeline('journey-story');
    setupTimeline('journey-milestones');
    setupTimeline('journey-github');   // generated by tools/sync
    setupTimeline('project-releases'); // generated project pages

    // ── 4. STATS COUNTER ─────────────────────────────────────
    const statsSection = document.querySelector('.stats-row');
    const statNumbers  = document.querySelectorAll('.stat-num');
    let started = false;

    if (statsSection) {
        window.addEventListener('scroll', () => {
            if (statsSection.getBoundingClientRect().top < window.innerHeight && !started) {
                statNumbers.forEach(num => {
                    const end = parseInt(num.getAttribute('data-val'));
                    if (end === 0) { num.textContent = '0'; return; }
                    let current = 0;
                    const interval = setInterval(() => {
                        current++;
                        num.textContent = current;
                        if (current >= end) { num.textContent = end; clearInterval(interval); }
                    }, 2000 / end);
                });
                started = true;
            }
        });
    }

    // ── 5. ISSUE 6: Dynamic footer year ──────────────────────
    // Runs on every page — gracefully skips if no #footer-year element
    const yearEl = document.getElementById('footer-year');
    if (yearEl) {
        yearEl.textContent = new Date().getFullYear();
    }

    // ── 6. ISSUE 1: btn-text arrow — ensure .btn-arrow spans exist
    // In case any page missed the manual wrap, this ensures the arrow
    // inside every .btn-text is wrapped for the CSS shift to apply.
    document.querySelectorAll('.btn-text').forEach(btn => {
        // Only process if no .btn-arrow already inside
        if (!btn.querySelector('.btn-arrow')) {
            btn.innerHTML = btn.innerHTML.replace(
                /(→|&rarr;|&#x2192;)/g,
                '<span class="btn-arrow">$1</span>'
            );
        }
    });

});
